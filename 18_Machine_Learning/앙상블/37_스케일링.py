'''
ML 모델은 숫자 크기 차이에 민감
나이 : 20 ~ 70 (범위 50)
연봉 : 1000000 ~ 9000000 (범위 8,000,000)
연봉이 나이보다 10만배 많을 경우 모델들은 큰 범위 숫자에 치중에서
계산하려는 습성이 있다.
스케일링은 이 범위를 균등하게 맞춰주는 작업

3가지 주요 스케일링
1. StandardScaler - 표준화
평균 0, 표준편차 1로 변환 가장 많이 사용
변환 공식 : (값 - 평균) / 표준편차

2. MinMaxScaler - 정규화
모든 값을 0 ~ 1 사이로 압축
변환 공식 : (값 - 최솟값) - (최댓값 - 최솟값)

3. RobustScaler - 이상치에 강한 스케일링
중앙값과 사분위수 기준으로 변환 → 이상치 영향최소화
변환 공식 : (값 - 중앙값) / (Q3 - Q1)
'''