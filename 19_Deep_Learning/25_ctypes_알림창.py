import ctypes

def 알림창기초():
    """
    ctypes = 파이썬이 윈도우 컴퓨터를 직접 조작할 수 있게 해주는 도구
    windll = 윈도우 기능이 들어있는 창고
             창고 안에 있는 기능들 중에서
             user32 = 화면/팝업 담당 기능
                MessageBoxW = 팝업창 띄우기 기능
    버튼 종류
    0 = 확인
    1 = 확인 + 취소
    2 = 중단 + 재시도 + 무시
    3 =   예 + 아니오 + 취소
    4 =   예 + 아니오
    """
    ctypes.windll.user32.MessageBoxW(
        0, # 부모창 어디서연다 하는데 보통 99 % 0 사용
        "내용창",
        "팝업제목",
        2 # 버튼 종류
    )
알림창기초()