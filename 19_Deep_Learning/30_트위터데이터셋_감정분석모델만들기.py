"""
=======================================================
학습 목표
=======================================================
1. 캐글에서 받은 실제 CSV 데이터를 pandas 로 불러오는 방법 익히기
2. 허깅페이스 pipeline 으로 이미 학습된 모델을 가져다 쓰는 방법 익히기
3. 직접 학습시키지 않아도 되는 사전학습 모델(pretrained model) 개념 이해하기
4. 예측 결과와 정답을 비교해서 정확도 계산하는 방법 익히기

=======================================================
사전 지식
=======================================================
pipeline   = 허깅페이스에서 제공하는 도구
모델 다운로드 + 전처리 + 예측 을 한방에 해결
직접 모델을 만들고 학습시킬 필요 없음

pretrained = 이미 누군가 학습시켜 놓은 모델
우리는 그냥 가져다 쓰기만 하면 됨
distilbert-base-uncased-finetuned-sst-2-english
= 영어 감성분석 전용으로 학습된 distilbert 모델

sentiment140 = 트위터에서 수집한 160만개 트윗 데이터셋
0 = 부정 트윗
4 = 긍정 트윗

=======================================================
실습 순서
=======================================================
1. CSV 데이터 불러오기
2. 허깅페이스 pipeline 준비
3. 트윗 예측하기
4. 정확도 계산하기
5. 직접 문장 입력해서 테스트하기
"""

import pandas as pd
import torch
from transformers import pipeline

# =======================================================
# 1. 데이터 불러오기
# =======================================================
df = pd.read_csv('training.1600000.processed.noemoticon.csv',
                 encoding='latin-1',
                 header=None,
                 names=['감성', '아이디', '날짜', '쿼리', '유저', '트윗'])

df = df[['트윗', '감성']].head(100)

df['감성'] = df['감성'].map({0: 0, 4: 1})

for i, 행 in df.head(3).iterrows():
    print(f"트윗 : {행['트윗'][:80]}")
    print(f"감성 : {행['감성']}  1=긍정, 0=부정")
    print('---')

# =======================================================
# 2. 허깅페이스 pipeline 준비
# =======================================================
장치 = 0 if torch.cuda.is_available() else -1

print(f"사용 장치: {'GPU' if 장치 == 0 else 'CPU'}")

감성분석기 = pipeline(
    'sentiment-analysis',
    model='distilbert-base-uncased-finetuned-sst-2-english',
    device=장치
)

# =======================================================
# 3. 예측하기
# =======================================================
트윗목록 = df['트윗'].tolist()

결과목록 = 감성분석기(트윗목록, truncation=True, max_length=64)

# =======================================================
# 4. 결과 출력 + 정확도 계산
# =======================================================
맞춘개수 = 0

for i, (트윗, 결과) in enumerate(zip(트윗목록, 결과목록)):
    예측 = 1 if 결과['label'] == 'POSITIVE' else 0
    정답 = df['감성'].iloc[i]
    맞춤 = 'O' if 예측 == 정답 else 'X'

    print(f"트윗 : {트윗[:60]}")
    print(f"예측 : {'긍정' if 예측 == 1 else '부정'}  정답: {'긍정' if 정답 == 1 else '부정'}  {맞춤}")
    print('---')

    if 예측 == 정답:
        맞춘개수 += 1

print(f"정확도 : {맞춘개수}/{len(트윗목록) * 100:.1f}%")

# =======================================================
# 5. 직접 문장 테스트
# =======================================================
내문장들 = [
    "I love this so much!!",
    "This is absolutely terrible",
    "Today was an okay day",
]

for 문장 in 내문장들:
    결과 = 감성분석기(문장)[0]
    print(f"문장 : {문장}")
    print(f"결과 : {'긍정' if 결과['label'] == 'POSITIVE' else '부정'}"
          f"(확률 : {결과['score']:.2f})")
    print('---')
