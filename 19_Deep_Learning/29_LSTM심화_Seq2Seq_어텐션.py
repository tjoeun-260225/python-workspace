"""
기존 LSTM 은 문장을 무조건 왼쪽 →오른쪽 방향으로만 읽는다.

사람은 문장을 앞 뒤 맥락을 다 보고 이해한다.
그것을 흉내낸 게 양방향 LSTM이다.

나는 미을에 가서 맛있는 것을 먹었다.
→ 아 마을을 쓰고 싶었는데 오타가 발생했구나! 유추

나는 학교에 간다
정방향 : 나 → 는 → 학교 → 에 → 간다. →
역방향 : 나 ← 는 ← 학교 ← 에 ← 간다. ←
와 같이 두 방향 결과를 합쳐서 사용

각 단어를 이해할 때 앞에 뭐가 있었는가 뒤에 뭐가 올 것인지를 참고
==================================================================
Seq2Seq(Sequence to Sequence)
==================================================================
입력 시퀀스를 받아서 출력 시퀀스를 만드는 구조

입력 : 나는 학교에 간다 (한국어)
출력 : I go to school   (영  어)

Seq2Seq는 두 파트로 나뉨

인코더(Encoder)
입력 문장을 통째로 읽고, 압축된 의미 벡터(context vector) 하나로 만들자

나 → 는 → 학교 → 에 → 간다
                       ↓
              [context vector]
      문장 전체 의미를 담은 숫자 덩어리

디코더(Decoder)
context vector 를 받아서 번역된 문장을 한 단어씩 만든다.

[context vector] → I → go → to → school <끝>
context = 맥락, 문맥
일상 단어
나는 배가   고프다 = 신체 배
배를 타고 여행했다 = 선박
같은 단어인데 주변 상황(context)에 따라 의미가 달라진다.
AI가 이 주변 상황 정보를 담아두는게 context 이다.
---------------------------------------------------------
vector = 의미가 담긴 숫자들의 목록
컴퓨터는 글자를 모르고 숫자만 안다.
그래서 모든 것을 숫자로 바꿔야 한다.
학교 → [0.2, 0.8, 0.1, 0.5, 0.3,...]
간다 → [0.1, 0.7, 0.1, 0.2, 0.3,...]
이 숫자 목록 하나를 벡터
비슷한 단어는 비슷한 숫자를 가진다.

context vector = 문장 전체를 숫자 목록으로 압축한 것
숫자 덩어리 안에 문장의 의미가 들어있다.
사람 눈에는 그냥 숫자지만 AI는 이 것을 보고 의미를 파악

SVG = 이미지 파일 Scalable Vector Graphics
- 웹에서 그림을 표현하는 방법 중 하나
- png, jpg 와 같은 이미지 확장자 파일

일반 이미지(jpg, png)
점으로 이루어진 그림 → 확대를 하면 깨짐

svg
- 숫자와 코딩으로 이루어진 이미지로
확대 축소를 하면 숫자값이 변경되어 깨지지 않는다.

vector
- 의미를 가진 숫자들
- 크기, 방향을 동시에 가지고 있는 숫자의 목록

GPT AI의 도움을 받아서 웹을 만든다. → svg 확장자 사용 xxx

현재 GPT 들의 모델은 svg 를 해석하다 무료 한도 종료
글자가 많은 svg 파일을 감당할 수준은 되지 않는다.
이미지 → 개발중일 상태일 때는 png 사용 → 개발이 종료되고 나서 이미지를 수정하거나
         해당 코딩 파일을 ai 도움 없이 코딩할 수 있는 수준이 된다면
         svg 파일로 교체

==================================================================
어텐션(Attention)
==================================================================
- 번역할 때 매 단어마다 원문의 어떤 단어를 집중해서 봐야할 것인가 결정

통역사가 번역할 때 전체 문장을 한 번에 외우는 게 아니라,
지금 번역하는 부분에서 원문에 어떤 단어를 다시 쳐다볼 것인가 결정하는 것과 같다.

나    는    학교   에 간다.
       school 을 번역할 때 학교에 집중 = 중요도 = 가중치를 높임

양방향 LSTM  → 앞 뒤 맥락 다 본다.
      ↓
  Seq2Seq    → 인코더가 압축, 디코더가 생성
      ↓
  Attention  → 매 순간 원문의 어느 부분에 집중하여 문맥을 파악할지 결정
      ↓
  기계 번역  → 위 세 가지를 합쳐서 구현
"""
import tensorflow as tf
import tensorflow_datasets as tfds  # pip install tensorflow_datasets
import numpy as np
from keras import Sequential
from tensorflow.keras.layers import Embedding, Bidirectional, LSTM, Dense, TextVectorization
from tensorflow.keras import Input, Model

# =======================================================
# 1. 데이터셋 로드
# =======================================================
# 텐서플로우에서 심오한 데이터셋을 가져올 때
# ModuleNotFoundError: No module named 'importlib_resources'
# 추가로 설치하여 가져와야 하는 순간이 발생할 수 있다.
# imdb = 영화 리뷰 긍정/부정
데이터셋 = tfds.load('imdb_reviews', as_supervised=True)
# as_supervised=True 데이터가져오는 상황 조회
# 가끔가다 텐서플로우에서 제공하는 데이터셋 사라졌을 수 도 있다.
# 텐서플로우나 케라스에서 제공하는 데이터셋 지원 유무 확인
# 데이터셋 = tfds.load('ted_hrlr_translate/pt_to_en', as_supervised=True)

for 리뷰, 점수 in 데이터셋['train'].take(2):
    print(f"리뷰 : {리뷰.numpy().decode('utf-8')[:80]}")  # 25000개 라서 80개만 조회
    print(f"점수 : {점수.numpy()} ←1=긍정, 0=부정")

# =======================================================
# 2. 텍스트 → 숫자 변환
# =======================================================
변환기 = TextVectorization(max_tokens=8000, output_sequence_length=200)
변환기.adapt(데이터셋['train'].map(lambda 리뷰, 점수: 리뷰))
# =======================================================
# 3. 로봇뇌 만들기
# =======================================================
로봇뇌 = Sequential([
    변환기,
    Embedding(8000, 64),
    Bidirectional(LSTM(128)),
    Dense(1, activation='sigmoid')
])
# =======================================================
# 4. 만들어진 로봇뇌를 사용할 수 있는 환경 세팅하기
# =======================================================
로봇뇌.compile(optimizer='adam',
            loss='binary_crossentropy',
            metrics=['accuracy'])
로봇뇌.summary()  # 만들어진 로봇뇌 어떻게 생겼는지 요약하여 조회하기
# =======================================================
# 5.  학습하기
# 대부분 batch_size 를 사용하지만
# 텐서플로우 데이터셋의 경우 .batch(자를숫자) 형태로 작성하도록
# 텐서플로우 데이터셋 내에 기입
# =======================================================
로봇뇌.fit(데이터셋['train'].batch(32), epochs=3)
# =======================================================
# 6.  예측하기
# =======================================================
테스트문장 = [
    'This movie was absolutely amazing!',  # 긍정
    'Terrible movie, waste of time',  # 부정
    'The acting was great but story boring',  # 애매
]
# 테스트문장이 필요한 이유는 우리가 데이터셋을 80% 20% 형태로 나누어서
# 훈련데이터 테스트 데이터로 나누지 않고, 데이터셋을 100% 훈련으로 사용했기 때문에
# 테스트 해야할 문장이 필요하여 테스트문장을 작성한 것
# 만약 테스트문장을 작성하고 싶지 않다면
# X_train, X_test 로 데이터셋 훈련용 훈련 잘 되었는지 확인용으로 분리하여 사용
결과 = 로봇뇌.predict(tf.constant(테스트문장))
# =======================================================
# 7.  웹사이트로 테스트를 하거나 가볍게 테스트 문장 작성해서 로봇뇌 만들어진 것 테스트하기
# =======================================================

for 문장, 확률 in zip(테스트문장, 결과):
    print(f"문장 : {문장}")
    print(f"결과 : {'긍정' if 확률[0] > 0.5 else '부정'} (확률:{확률[0]:.2f})")
    print('-' * 10)
